    private static function polynomial(float $z, array $coefficients): float
    {
        $acc = 0.0;
        for ($i = count($coefficients) - 1; $i >= 0; $i--) {
            $acc = $acc * $z + $coefficients[$i];
        }

        return $acc;
    }

    public static function lnGamma(float $x): float
    {
        $dk = self::GAMMA_DK;
        $s = $dk[0];
        if ($x < 0.5) {
            for ($i = 1; $i < 11; $i++) {
                $s += $dk[$i] / ($i - $x);
            }

            return self::LN_PI - log(sin(M_PI * $x)) - log($s) - self::LN_2_SQRT_E_OVER_PI
                - (0.5 - $x) * log((0.5 - $x + self::GAMMA_R) / M_E);
        }
        for ($i = 1; $i < 11; $i++) {
            $s += $dk[$i] / ($x + $i - 1.0);
        }

        return log($s) + self::LN_2_SQRT_E_OVER_PI + ($x - 0.5) * log(($x - 0.5 + self::GAMMA_R) / M_E);
    }

    public static function erfc(float $x): float
    {
        if (is_nan($x)) {
            return NAN;
        }
        if ($x === INF) {
            return 0.0;
        }
        if ($x === -INF) {
            return 2.0;
        }

        return self::erfImpl($x, true);
    }

    private static function erfImpl(float $z, bool $inv): float
    {
        if ($z < 0.0) {
            if (! $inv) {
                return -self::erfImpl(-$z, false);
            }
            if ($z < -0.5) {
                return 2.0 - self::erfImpl(-$z, true);
            }

            return 1.0 + self::erfImpl(-$z, false);
        }
        if ($z < 0.5) {
            $result = $z < 1e-10
                ? $z * 1.125 + $z * 0.003379167095512573896158903121545171688
                : $z * 1.125 + $z * self::polynomial($z, self::AN) / self::polynomial($z, self::AD);
        } elseif ($z < 110.0) {
            [$shift, $n, $d, $b] = match (true) {
                $z < 0.75 => [0.5, self::BN, self::BD, 0.3440242112],
                $z < 1.25 => [0.75, self::CN, self::CD, 0.419990927],
                $z < 2.25 => [1.25, self::DN, self::DD, 0.4898625016],
                $z < 3.5 => [2.25, self::EN, self::ED, 0.5317370892],
                $z < 5.25 => [3.5, self::FN, self::FD, 0.5489973426],
                $z < 8.0 => [5.25, self::GN, self::GD, 0.5571740866],
                $z < 11.5 => [8.0, self::HN, self::HD, 0.5609807968],
                $z < 17.0 => [11.5, self::IN, self::ID, 0.5626493692],
                $z < 24.0 => [17.0, self::JN, self::JD, 0.5634598136],
                $z < 38.0 => [24.0, self::KN, self::KD, 0.5638477802],
                $z < 60.0 => [38.0, self::LN, self::LD, 0.5640528202],
                $z < 85.0 => [60.0, self::MN, self::MD, 0.5641309023],
                default => [85.0, self::NN, self::ND, 0.5641584396],
            };
            $r = self::polynomial($z - $shift, $n) / self::polynomial($z - $shift, $d);
            $g = exp(-$z * $z) / $z;
            $result = $g * $b + $g * $r;
        } else {
            $result = 0.0;
        }
        if ($inv && $z >= 0.5) {
            return $result;
        }
        if ($z >= 0.5 || $inv) {
            return 1.0 - $result;
        }

        return $result;
    }

    /** Standard normal survival function, statrs Normal::sf. */
    public static function normalSf(float $x): float
    {
        return 0.5 * self::erfc($x / M_SQRT2);
    }

    /** Regularized incomplete beta I_x(a, b) (Numerical Recipes continued fraction). */
    public static function betaReg(float $a, float $b, float $x): float
    {
        $bt = ($x == 0.0 || abs($x - 1.0) <= 1e-15)
            ? 0.0
            : exp(self::lnGamma($a + $b) - self::lnGamma($a) - self::lnGamma($b) + $a * log($x) + $b * log(1.0 - $x));
        $symmetric = $x >= ($a + 1.0) / ($a + $b + 2.0);
        $eps = self::F64_PREC;
        $fpmin = PHP_FLOAT_MIN / $eps;
        if ($symmetric) {
            $x = 1.0 - $x;
            [$a, $b] = [$b, $a];
        }
        $qab = $a + $b;
        $qap = $a + 1.0;
        $qam = $a - 1.0;
        $c = 1.0;
        $d = 1.0 - $qab * $x / $qap;
        if (abs($d) < $fpmin) {
            $d = $fpmin;
        }
        $d = 1.0 / $d;
        $h = $d;
        for ($m = 1.0; $m < 141.0; $m += 1.0) {
            $m2 = $m * 2.0;
            $aa = $m * ($b - $m) * $x / (($qam + $m2) * ($a + $m2));
            $d = 1.0 + $aa * $d;
            if (abs($d) < $fpmin) {
                $d = $fpmin;
            }
            $c = 1.0 + $aa / $c;
            if (abs($c) < $fpmin) {
                $c = $fpmin;
            }
            $d = 1.0 / $d;
            $h = $h * $d * $c;
            $aa = -($a + $m) * ($qab + $m) * $x / (($a + $m2) * ($qap + $m2));
            $d = 1.0 + $aa * $d;
            if (abs($d) < $fpmin) {
                $d = $fpmin;
            }
            $c = 1.0 + $aa / $c;
            if (abs($c) < $fpmin) {
                $c = $fpmin;
            }
            $d = 1.0 / $d;
            $del = $d * $c;
            $h *= $del;
            if (abs($del - 1.0) <= $eps) {
                break;
            }
        }

        return $symmetric ? 1.0 - $bt * $h / $a : $bt * $h / $a;
    }

    /** Student's t survival function (location 0, scale 1), statrs StudentsT::sf. */
    public static function tSf(float $x, float $df): float
    {
        $h = $df / ($df + $x * $x);
        $ib = 0.5 * self::betaReg($df / 2.0, 0.5, $h);

        return $x <= 0.0 ? 1.0 - $ib : $ib;
    }

    /** qt(0.975, df) by bisection on the survival function, as the extension's OLS does. */
    public static function tCritical95(float $df): float
    {
        $lower = 0.0;
        $upper = 1.0;
        while (self::tSf($upper, $df) > 0.025) {
            $upper *= 2.0;
        }
        for ($i = 0; $i < 64; $i++) {
            $mid = ($lower + $upper) / 2.0;
            if (self::tSf($mid, $df) > 0.025) {
                $lower = $mid;
            } else {
                $upper = $mid;
            }
        }

        return ($lower + $upper) / 2.0;
    }

