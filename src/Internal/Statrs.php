    /** Inverse complementary error function, statrs erfc_inv. */
    public static function erfcInv(float $x): float
    {
        if ($x <= 0.0) {
            return INF;
        }
        if ($x >= 2.0) {
            return -INF;
        }
        if ($x > 1.0) {
            return self::erfInvImpl(-1.0 + $x, 2.0 - $x, -1.0);
        }

        return self::erfInvImpl(1.0 - $x, $x, 1.0);
    }

    private static function erfInvImpl(float $p, float $q, float $s): float
    {
        if ($p <= 0.5) {
            $g = $p * ($p + 10.0);
            $r = self::polynomial($p, self::INV_AN) / self::polynomial($p, self::INV_AD);
            $result = $g * 0.0891314744949340820313 + $g * $r;
        } elseif ($q >= 0.25) {
            $g = sqrt(-2.0 * log($q));
            $xs = $q - 0.25;
            $r = self::polynomial($xs, self::INV_BN) / self::polynomial($xs, self::INV_BD);
            $result = $g / (2.249481201171875 + $r);
        } else {
            $x = sqrt(-log($q));
            [$y, $shift, $n, $d] = match (true) {
                $x < 3.0 => [0.807220458984375, 1.125, self::INV_CN, self::INV_CD],
                $x < 6.0 => [0.93995571136474609375, 3.0, self::INV_DN, self::INV_DD],
                $x < 18.0 => [0.98362827301025390625, 6.0, self::INV_EN, self::INV_ED],
                $x < 44.0 => [0.99714565277099609375, 18.0, self::INV_FN, self::INV_FD],
                default => [0.99941349029541015625, 44.0, self::INV_GN, self::INV_GD],
            };
            $xs = $x - $shift;
            $r = self::polynomial($xs, $n) / self::polynomial($xs, $d);
            $result = $y * $x + $r * $x;
        }

        return $s * $result;
    }

    /** Standard normal quantile, statrs Normal::inverse_cdf. */
    public static function normalQuantile(float $p): float
    {
        return -(M_SQRT2 * self::erfcInv(2.0 * $p));
    }
